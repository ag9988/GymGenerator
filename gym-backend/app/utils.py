def convert_weight(value: float, from_unit: str, to_unit: str) -> float:
    """Convert weight between lb and kg."""
    if from_unit == to_unit:
        return value
    if from_unit == "lb" and to_unit == "kg":
        return round(value / 2.20462, 2)
    elif from_unit == "kg" and to_unit == "lb":
        return round(value * 2.20462, 2)
    return value

def calc_load_points(session_data: dict) -> float:
    """Calculate training load points based on session type."""
    session_type = session_data.get("type")

    # Free workout: duration_min * rpe / 4
    if session_type == "free":
        free_data = session_data.get("free", {})
        duration_min = free_data.get("duration_minutes", 0)
        rpe = free_data.get("rpe", 5)
        return max(0, round(duration_min * rpe / 4))

    # Breathwork: always 0
    if session_type == "breathwork":
        return 0

    # Cardio formulas
    if session_type in ["run", "cycle", "hike", "swim"]:
        cardio_data = session_data.get("cardio", {})
        distance = cardio_data.get("distance", 0)

        if session_type == "run":
            # miles * (12 / pace_min_per_mile) * 10
            # For now, simplified: miles * 10
            return round(distance * 10)
        elif session_type == "cycle":
            # miles * 4
            return round(distance * 4)
        elif session_type == "hike":
            # (miles * 0.6 + elevation_ft / 1500) * 10
            elev = cardio_data.get("elevation", 0) or 0
            return round((distance * 0.6 + elev / 1500) * 10)
        elif session_type == "swim":
            # meters / 8
            return round(distance / 8)

    # Gym workout: total_volume / 500
    if session_type in ["upper", "lower", "full", "group_a", "group_b", "group_c"]:
        total_volume = 0
        exercises = session_data.get("exercises", [])
        unit = session_data.get("unit", "lb")

        for ex in exercises:
            for s in ex.get("sets", []):
                try:
                    weight = float(s.get("weight", 0) or 0)
                    reps_str = s.get("reps", "0")
                    reps = float(reps_str.split("-")[0]) if reps_str else 0
                    total_volume += weight * reps
                except (ValueError, IndexError):
                    pass

        # Normalize to lb if needed
        if unit == "kg":
            total_volume = total_volume * 2.20462

        return max(0, round(total_volume / 500))

    return 0
